//! Emit a topic's output fields as TypeScript type declarations — one `export type` per field.
//! A field whose every producer variant bottoms out in a `Sanitizer::Mapping` chain with
//! `on_miss: "drop"` (or absent, which defaults to drop — see `lang::sanitize::Sanitizer::Mapping`'s
//! own doc) is a closed set of string values, i.e. an enum; that becomes a string-literal union.
//! Anything else (an open-ended sanitizer, a non-string mapping value, or a field with no closed
//! source at all) falls back to a plain `string` — best-effort, not a precise model of every
//! possible producer shape.
//!
//! Usage: `export_ts_types <config-dir> <topic-name>`, e.g. `export_ts_types configs tilda/bikelanes`.
//! Prints the `.ts` source to stdout.

use std::collections::BTreeSet;

use anyhow::{Context, Result};
use serde_json::Value;

use osmnexus::lang::producer::Producer;
use osmnexus::lang::sanitize::{AtomicJson, Sanitizer};
use osmnexus::topic::runner::TopicRunner;
use osmnexus::topic::spec::Field;

/// What one producer variant contributes toward a field's type: a closed set of string values, or
/// "open" (no closed set — falls the whole field back to `string`).
enum Contribution {
    Closed(BTreeSet<String>),
    Open,
}

fn main() -> Result<()> {
    let mut args = std::env::args().skip(1);
    let usage = "usage: export_ts_types <config-dir> <topic-name>";
    let config_dir = args.next().context(usage)?;
    let topic_name = args.next().context(usage)?;

    osmnexus::paths::set_config_root(config_dir);
    // `0` skips compiling any decision tree — this binary only inspects `default_producers`/
    // `category_producers`' field shapes, never a compiled tree.
    let runner = TopicRunner::load(&topic_name, 0)
        .with_context(|| format!("loading topic '{topic_name}'"))?;

    let mut contributions: std::collections::BTreeMap<String, Vec<Contribution>> = std::collections::BTreeMap::new();
    for field in runner.default_producers.iter().chain(runner.category_producers.iter().flatten()) {
        contributions.entry(field.output.clone()).or_default().push(collect(field));
    }

    println!("// Generated by export_ts_types from topic '{topic_name}' — do not edit by hand.\n");
    for (name, parts) in contributions {
        println!("export type {} = {};", to_pascal_case(&name), render(&parts));
    }
    Ok(())
}

/// Walk one field's `Producer` tree, collecting the closed value set (or lack thereof) of every
/// leaf's terminal sanitize-chain step, unioned into a single `Contribution` for this variant.
fn collect(field: &Field) -> Contribution {
    let mut values = BTreeSet::new();
    let mut open = false;
    walk(&field.source, &mut values, &mut open);
    if open { Contribution::Open } else { Contribution::Closed(values) }
}

fn walk(producer: &Producer, values: &mut BTreeSet<String>, open: &mut bool) {
    match producer {
        Producer::Extract { extract, .. } => match extract.sanitize().last() {
            None => *open = true, // identity read — unbounded raw tag value
            Some(Sanitizer::Mapping { mapping, on_miss }) if on_miss.is_none() || on_miss.as_deref() == Some("drop") => {
                for entry in mapping.values().flatten() {
                    match entry {
                        AtomicJson::Str(s) => {
                            values.insert(s.clone());
                        }
                        AtomicJson::Bool(_) | AtomicJson::Num(_) => *open = true,
                    }
                }
            }
            Some(_) => *open = true, // open-ended: Replace, Builtin, or Mapping with keep/constant on_miss
        },
        Producer::Match { rules, default, .. } => {
            for rule in rules {
                walk(&rule.value, values, open);
            }
            if let Some(Value::String(s)) = default {
                values.insert(s.clone());
            } else if default.is_some() {
                *open = true;
            }
        }
        Producer::Const { value, .. } => match value {
            Value::String(s) => {
                values.insert(s.clone());
            }
            _ => *open = true,
        },
        Producer::Parent(inner) => walk(inner, values, open),
    }
}

/// Render the unioned contributions of every variant of a field into a TS type body: a
/// string-literal union if every variant contributed a closed set, `string` otherwise.
fn render(parts: &[Contribution]) -> String {
    if parts.iter().any(|c| matches!(c, Contribution::Open)) {
        return "string".to_owned();
    }
    let mut values: BTreeSet<&str> = BTreeSet::new();
    for part in parts {
        if let Contribution::Closed(set) = part {
            values.extend(set.iter().map(String::as_str));
        }
    }
    if values.is_empty() {
        return "string".to_owned();
    }
    values.iter().map(|v| serde_json::to_string(v).unwrap()).collect::<Vec<_>>().join(" | ")
}

fn to_pascal_case(s: &str) -> String {
    s.split(|c: char| c == '_' || c == '-')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect()
}
