//! TypeScript backend: one `export type` per output field, from the topic's inferred
//! `OutputSchema` — a closed value set becomes a string-literal union, anything else `string`.

use osmnexus_lang::topic::schema::{FieldType, OutputSchema};
use osmnexus_lang::topic::Topic;

use crate::Backend;

/// The `.ts` source for `schema`, byte-for-byte what `export_ts_types` has always printed.
pub fn render_ts(topic_name: &str, schema: &OutputSchema) -> String {
    let mut out = format!("// Generated by export_ts_types from topic '{topic_name}' — do not edit by hand.\n\n");
    for (name, ty) in &schema.fields {
        out.push_str(&format!("export type {} = {};\n", to_pascal_case(name), render_type(ty)));
    }
    out
}

/// TS types for a whole topic, as a `Backend`.
pub struct TsTypes;

impl Backend for TsTypes {
    fn file_extension(&self) -> &'static str {
        "ts"
    }

    fn generate(&self, topic_name: &str, topic: &Topic) -> String {
        render_ts(topic_name, &topic.output_schema())
    }
}

/// A TS type body: a string-literal union for a closed set, `string` otherwise.
fn render_type(ty: &FieldType) -> String {
    match ty {
        FieldType::String => "string".to_owned(),
        FieldType::Enum(values) => {
            values.iter().map(|v| serde_json::to_string(v).unwrap()).collect::<Vec<_>>().join(" | ")
        }
    }
}

fn to_pascal_case(s: &str) -> String {
    s.split(|c: char| c == '_' || c == '-')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect()
}
